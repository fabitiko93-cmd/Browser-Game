// Offline only: official CC0 HDRs -> mobile sRGB panoramas, no runtime HDR decoder.
// Usage: node scripts/prepare-planet-skies.mjs artifacts/sky
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { HDRLoader } from 'three/addons/loaders/HDRLoader.js';
import { FloatType } from 'three';

const folder = resolve(process.argv[2] ?? 'artifacts/sky');
const sources = [
  ['fair', 'kloofendal_48d_partly_cloudy_puresky', .9, ['Greg Zaal', 'Jarod Guest']],
  ['overcast', 'kloofendal_overcast_puresky', .55, ['Greg Zaal']]
];
const catalog = {}, provenance = [];
for (const [id, name, exposure, authors] of sources) {
  const bytes = await readFile(resolve(folder, name + '.hdr'));
  const hdr = new HDRLoader().setDataType(FloatType).parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
  const { width, height, data } = hdr;
  if (width !== 2048 || height !== 1024) throw new Error('Use the official 2K HDR source.');
  let brightest = -1, sunPixel = 0;
  const rgb = new Uint8Array(width * height * 3);
  for (let i = 0; i < width * height; i++) {
    const lum = data[i * 4] * .2126 + data[i * 4 + 1] * .7152 + data[i * 4 + 2] * .0722;
    if (i < width * height / 2 && lum > brightest) { brightest = lum; sunPixel = i; }
    for (let c = 0; c < 3; c++) {
      const x = data[i * 4 + c] * exposure;
      const linear = Math.max(0, Math.min(1, (x * (2.51 * x + .03)) / (x * (2.43 * x + .59) + .14)));
      const srgb = linear <= .0031308 ? linear * 12.92 : 1.055 * linear ** (1 / 2.4) - .055;
      rgb[i * 3 + c] = Math.round(srgb * 255);
    }
  }
  // Remove the photographer's blurred mirrored lower hemisphere. The same
  // neutral horizon colour is used by distance fog, avoiding a second horizon.
  const horizon = [0, 0, 0], band = 6;
  for (let y = height / 2 - band; y < height / 2; y++) for (let x = 0; x < width; x++) for (let c = 0; c < 3; c++) horizon[c] += rgb[(y * width + x) * 3 + c] / (band * width);
  for (let y = 0; y < height; y++) {
    const t = Math.max(0, Math.min(1, (height / 2 - y) / 26)), weight = t * t * (3 - 2 * t);
    for (let x = 0; x < width; x++) for (let c = 0; c < 3; c++) { const p = (y * width + x) * 3 + c; rgb[p] = Math.round(horizon[c] + (rgb[p] - horizon[c]) * weight); }
  }
  const ppm = resolve(folder, id + '.ppm'), file = `sky-${id}.webp`;
  await writeFile(ppm, Buffer.concat([Buffer.from(`P6\n${width} ${height}\n255\n`), rgb]));
  execFileSync('python', ['-c', 'from PIL import Image;import sys;Image.open(sys.argv[1]).save(sys.argv[2],quality=88,method=6)', ppm, resolve('web/models/planets', file)]);
  catalog[id] = { file, horizon: '#' + horizon.map(v => Math.round(v).toString(16).padStart(2, '0')).join(''), elevation: (90 - (Math.floor(sunPixel / width) + .5) / height * 180) * Math.PI / 180, azimuth: ((sunPixel % width + .5) / width * 2 - 1) * Math.PI };
  provenance.push({ id, file, width, height, source: `https://polyhaven.com/a/${name}`, download: `https://dl.polyhaven.org/file/ph-assets/HDRIs/hdr/2k/${name}_2k.hdr`, authors, license: 'CC0-1.0', sourceSha256: createHash('sha256').update(bytes).digest('hex'), outputSha256: createHash('sha256').update(await readFile(resolve('web/models/planets', file))).digest('hex'), exposure, preparation: 'ACES fitted curve to sRGB, 2048x1024 WebP quality 88; lower hemisphere and lowest 4.6 degrees blend to the measured horizon mean.' });
}
await writeFile('src/planet-sky-data.js', '// Generated by scripts/prepare-planet-skies.mjs.\nexport const PLANET_SKIES = Object.freeze(' + JSON.stringify(catalog, null, 2) + ');\n');
await writeFile('web/models/planets/sky-provenance.json', JSON.stringify(provenance, null, 2) + '\n');
console.log(catalog);
