import { readdir, readFile, mkdir, rm, writeFile } from 'node:fs/promises';
import { resolve, relative, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';
const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'docs');
const check = process.argv.includes('--check');
async function files(folder) {
  const result = [];
  for (const e of await readdir(folder, { withFileTypes: true })) {
    const p = resolve(folder, e.name);
    if (e.isDirectory()) result.push(...await files(p)); else result.push(p);
  }
  return result.sort();
}
const contents = new Map();
for (const path of await files(resolve(root, 'src'))) contents.set('build/' + relative(resolve(root, 'src'), path), await readFile(path));
for (const path of await files(resolve(root, 'web'))) contents.set(relative(resolve(root, 'web'), path), await readFile(path));
// Bundle rendering locally; the strategic game keeps its existing ES modules.
for (const entry of ['battle-scene', 'harbinger-scene']) {
  const result = await build({entryPoints:[resolve(root,`src/${entry}.js`)],bundle:true,write:false,format:'esm',platform:'browser',minify:true,target:['safari15'],legalComments:'inline'});
  contents.set(`build/${entry}.js`,Buffer.from(result.outputFiles[0].contents));
}
contents.set('.nojekyll', Buffer.alloc(0));
// Keep one range implementation for Node, module tests and the existing classic worker.
contents.set('media-range.js',Buffer.from((await readFile(resolve(root,'src/media-range.js'),'utf8')).replace(/^export /m,'')));
const digest=createHash('sha256');
for(const [path,content] of contents)digest.update(path+'\n').update(content).update('\n');
const hash = digest.digest('hex').slice(0, 16);
// Streamed optional model parts are cached only after they are requested.
const assets = ['./', ...[...contents.keys()].filter(p=>p!=='.nojekyll'&&!p.endsWith('.part')).map(p=>'./'+p)];
contents.set('sw.js', `// Generated by scripts/build.mjs. Do not edit.
importScripts('./media-range.js');
const CACHE='orbit3077-${hash}';
const ASSETS=${JSON.stringify(assets)};
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS.map(url=>new Request(url,{cache:'reload'})))).then(()=>self.skipWaiting())));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('orbit3077-')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{
 if(event.request.method!=='GET'||new URL(event.request.url).origin!==self.location.origin)return;
 event.respondWith(caches.open(CACHE).then(async cache=>{
  const stored=await cache.match(event.request,event.request.mode==='navigate'?{ignoreSearch:true}:undefined);
  if(stored)return mediaRange(event.request,stored);
  try{
   const response=await fetch(event.request);
   if(response.status===200)event.waitUntil(cache.put(event.request,response.clone()).catch(()=>{}));
   return mediaRange(event.request,response);
  }catch(error){if(event.request.mode==='navigate')return(await cache.match('./index.html'))||Promise.reject(error);throw error;}
 }));
});
`);

if (check) {
  let valid = true;
  for (const [path, content] of contents) {
    try { if (!(await readFile(resolve(output, path))).equals(Buffer.from(content))) { console.error('Out of date:', path); valid = false; } }
    catch { console.error('Missing:', path); valid = false; }
  }
  try { for (const p of await files(output)) if (!contents.has(relative(output, p))) { console.error('Unexpected output:', relative(output, p)); valid = false; } } catch { valid = false; }
  if (!valid) process.exitCode = 1; else console.log(`Build verified (${contents.size} files, ${hash}).`);
} else {
  await rm(output, { recursive: true, force: true });
  for (const [path, content] of contents) { await mkdir(dirname(resolve(output, path)), { recursive: true }); await writeFile(resolve(output, path), content); }
  console.log(`Built ${contents.size} files (${hash}).`);
}
