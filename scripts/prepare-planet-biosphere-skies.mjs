// Derive matching panorama/environment/fog grades from the prepared CC0 skies.
// Run after prepare-planet-skies.mjs; no HDR originals are needed for this step.
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { Color } from 'three';
import { PLANET_SKIES } from '../src/planet-sky-data.js';
import { BIOSPHERES } from '../src/planet-biomes.js';
const skies = Object.fromEntries(['fair', 'overcast'].map(id => [id, PLANET_SKIES[id]]));
const records = JSON.parse(await readFile('web/models/planets/sky-provenance.json', 'utf8')).filter(r => ['fair', 'overcast'].includes(r.id));
const originals = [...records];
for (const [biosphere, biology] of Object.entries(BIOSPHERES).filter(([, b]) => b.alien)) for (const weather of ['fair', 'overcast']) {
  const source = skies[weather], id = `${biosphere}-${weather}`, file = `sky-${id}.webp`, tint = new Color(biology.skyTint);
  execFileSync('python', ['-c', `from PIL import Image
import numpy as np,sys
a=np.array(Image.open(sys.argv[1]).convert('RGB'),dtype=float)/255
a=np.where(a<=.04045,a/12.92,((a+.055)/1.055)**2.4)*np.array([float(x) for x in sys.argv[3:]])
a=np.where(a<=.0031308,a*12.92,1.055*np.maximum(a,0)**(1/2.4)-.055)
Image.fromarray(np.uint8(np.clip(np.rint(a*255),0,255))).save(sys.argv[2],quality=88,method=6)`, `web/models/planets/${source.file}`, `web/models/planets/${file}`, ...tint.toArray().map(String)]);
  skies[id] = { ...source, file, horizon: '#' + new Color(source.horizon).multiply(tint).getHexString() };
  records.push({ ...originals.find(r => r.id === weather), id, file, outputSha256: createHash('sha256').update(await readFile(`web/models/planets/${file}`)).digest('hex'), derivedFrom: source.file, linearTint: tint.toArray(), preparation: `Prepared ${weather} panorama multiplied in linear light by the ${biosphere} atmosphere grade; sRGB WebP quality 88. Sun position and cloud detail are preserved.` });
}
await writeFile('src/planet-sky-data.js', '// Generated by scripts/prepare-planet-skies.mjs and prepare-planet-biosphere-skies.mjs.\nexport const PLANET_SKIES = Object.freeze(' + JSON.stringify(skies, null, 2) + ');\n');
await writeFile('web/models/planets/sky-provenance.json', JSON.stringify(records, null, 2) + '\n');
